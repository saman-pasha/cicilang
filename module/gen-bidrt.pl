#!/usr/bin/perl
# gen-bidrt.pl: writes library/ccl_bidrt.pl from the IR that cicilang makes of module/bidrt.c (0.137, 0.243): one fact per
# function, `ccl_bidrt_text(Name, Text)', every function made `internal', so two objects that call one routine link; one
# per function, `ccl_bidrt_calls(Name, Names)', the names of the table it calls; and one per declaration, should the IR
# hold one. The lowering notes a routine with the routines it calls into a module that asks it.
#     sh module/gen-bidrt.sh
use strict; use warnings;
my (@facts, %defined, $name, $text);
sub pq { my $s = $_[0]; $s =~ s/\\/\\\\/g; $s =~ s/'/\\'/g; $s =~ s/\n/\\n/g; return "'$s'" }
while (my $l = <STDIN>) {
    chomp $l;
    if (defined $text) { $text .= "\n$l"; if ($l eq '}') { push @facts, [$name, $text, 1]; $defined{$name} = 1; undef $text } next }
    if ($l =~ /^define (?:internal )?(.*?@([\w.]+)\(.*)$/) { $name = $2; $text = "define internal $1"; next }
    if ($l =~ /^declare .*?@([\w.]+)\(/) { push @facts, [$1, $l, 0]; $defined{$1} = 1; next }
}
die "no function read\n" unless @facts;
print "%% ccl_bidrt.pl -- THE DECIMAL RUNTIME OF THE COMPILER (0.243; its first routines, a 128-bit integer's conversions, 0.137):\n";
print "%% every routine the lowering calls for _Decimal32, _Decimal64 and _Decimal128, libgcc's by name (`__ccl_bid_adddd3' ...).\n";
print "%% GENERATED by module/gen-bidrt.sh from module/bidrt.c, compiled by cicilang itself; never edited by hand.\n";
print "%% ccl_bidrt_text(Name, Text): a function, internal, or a declaration; ccl_bidrt_calls(Name, Names): the functions of the\n";
print "%% table it calls. The lowering notes a routine and the routines it calls (ir_dec_rt/1, library/ccl_ir.pl).\n";
printf "ccl_bidrt_text(%s, %s).\n", pq($_->[0]), pq($_->[1]) for @facts;
for my $f (grep { $_->[2] } @facts) {
    my %seen; my @calls;
    while ($f->[1] =~ /\@([\w.]+)\(/g) { my $c = $1; next if $c eq $f->[0] || $seen{$c}++ || !$defined{$c}; push @calls, $c }
    printf "ccl_bidrt_calls(%s, [%s]).\n", pq($f->[0]), join(', ', map { pq($_) } @calls);
}
