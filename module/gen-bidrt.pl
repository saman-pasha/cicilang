#!/usr/bin/perl
# gen-bidrt.pl: writes library/ccl_bidrt.pl from the IR that cicilang makes of module/bidrt.c (0.137): one fact per
# function and per declaration, `ccl_bidrt_text(Name, Text)', every function made `internal', so two objects that
# convert link. The lowering notes them all into a module that converts a decimal to or from a 128-bit integer.
#     sh module/gen-bidrt.sh
use strict; use warnings;
my (@facts, $name, $text);
sub pq { my $s = $_[0]; $s =~ s/\\/\\\\/g; $s =~ s/'/\\'/g; $s =~ s/\n/\\n/g; return "'$s'" }
while (my $l = <STDIN>) {
    chomp $l;
    if (defined $text) { $text .= "\n$l"; if ($l eq '}') { push @facts, [$name, $text]; undef $text } next }
    if ($l =~ /^define (?:internal )?(.*?@([\w.]+)\(.*)$/) { $name = $2; $text = "define internal $1"; next }
    if ($l =~ /^declare .*?@([\w.]+)\(/) { push @facts, [$1, $l]; next }
}
die "no function read\n" unless @facts;
print "%% ccl_bidrt.pl -- THE DECIMAL CONVERSIONS OF A 128-BIT INTEGER (0.137): a _Decimal32, _Decimal64 or _Decimal128 to\n";
print "%% and from __int128 and unsigned __int128, which libgcc does not have. GENERATED by module/gen-bidrt.sh from\n";
print "%% module/bidrt.c, compiled by cicilang itself; never edited by hand. ccl_bidrt_text(Name, Text): a function, internal,\n";
print "%% or a declaration of a libgcc routine it calls; the lowering notes every one (ir_dec_rt128, library/ccl_ir.pl).\n";
printf "ccl_bidrt_text(%s, %s).\n", pq($_->[0]), pq($_->[1]) for @facts;
